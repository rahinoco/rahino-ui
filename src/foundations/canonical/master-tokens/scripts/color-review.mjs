import { loadModel, contrastRatio, roundRatio } from './foundations.mjs';
import { resolve, display } from './lib.mjs';
import { resolveContext } from './context.mjs';

const surfaces = ['canvas', 'base', 'subtle', 'raised', 'sunken'];
const statuses = ['success', 'warning', 'error', 'info'];
const table = (headers, rows) => [`| ${headers.join(' | ')} |`, `| ${headers.map(() => '---').join(' | ')} |`, ...rows.map(row => `| ${row.join(' | ')} |`)].join('\n');
const code = value => `\`${value}\``;
const ratioLabel = test => `${test.ratio.toFixed(4)}:1${test.passes ? '' : ' — below target'}`;

export async function renderColorReview(model) {
  model ??= await loadModel();
  const contexts = [], inkRows = [], boundaryRows = [];
  for (const appearance of ['light', 'dark']) for (const contrast of ['standard', 'more']) {
    const tokens = new Map(model.contexts[appearance]);
    if (contrast === 'more') {
      const policy = resolveContext({ appearance, contrast });
      for (const [p, alias] of Object.entries(policy.overrides)) tokens.set(p, { ...tokens.get(p), $value: alias });
    }
    const value = p => { const token = resolve(tokens, p); return display(token.$type, token.$value); };
    const context = { appearance, contrast, tests: [] };
    const test = (family, foreground, background, threshold) => {
      const foregroundValue = value(foreground), backgroundValue = value(background);
      const ratio = contrastRatio(foregroundValue, backgroundValue);
      const entry = { family, foreground, background, foregroundValue, backgroundValue, ratio, threshold, passes: ratio >= threshold };
      context.tests.push(entry);
      return entry;
    };
    for (const ink of ['primary', 'secondary', 'tertiary']) {
      inkRows.push([appearance, contrast, code(`ink.${ink}`), ...surfaces.map(surface => ratioLabel(test('Neutral resting text', `rds.color.ink.${ink}`, `rds.color.surface.${surface}`, 4.5)))]);
    }
    for (const role of ['focus.ring', 'edge.control']) {
      boundaryRows.push([appearance, contrast, code(role), ...surfaces.map(surface => ratioLabel(test(role === 'focus.ring' ? 'Focus on neutral parent' : 'Control edge on neutral parent', `rds.color.${role}`, `rds.color.surface.${surface}`, 3)))]);
    }
    for (const state of ['default', 'hover', 'pressed']) test('Enabled primary label', 'rds.color.action.primary.fg', `rds.color.action.primary.bg.${state}`, 4.5);
    for (const status of statuses) {
      test('Status text on soft background', `rds.color.status.${status}.fg`, `rds.color.status.${status}.bg`, 4.5);
      test('Status text on solid fill', `rds.color.status.${status}.on-fill`, `rds.color.status.${status}.fill`, 4.5);
      test('Focus on status parent', 'rds.color.focus.ring', `rds.color.status.${status}.bg`, 3);
    }
    for (const state of ['default', 'hover']) {
      test('Brand text on soft background', 'rds.color.brand.fg', `rds.color.brand.bg.${state}`, 4.5);
      test('Focus on brand parent', 'rds.color.focus.ring', `rds.color.brand.bg.${state}`, 3);
    }
    context.failures = context.tests.filter(test => !test.passes);
    contexts.push(context);
  }
  const failures = contexts.flatMap(context => context.failures.map(test => ({ appearance: context.appearance, contrast: context.contrast, ...test })));
  const textTable = table(['Theme', 'Contrast', 'Ink', ...surfaces], inkRows);
  const boundaryTable = table(['Theme', 'Contrast', 'Role', ...surfaces], boundaryRows);
  const failureTable = table(['Theme', 'Contrast', 'Foreground', 'Background', 'Ratio', 'Target'], failures.map(test => [test.appearance, test.contrast, `${code(test.foreground)}<br>${code(test.foregroundValue)}`, `${code(test.background)}<br>${code(test.backgroundValue)}`, test.ratio.toFixed(4) + ':1', test.threshold + ':1']));
  // Pass/fail uses unrounded ratios; the serialized record stores a stable 10-decimal value.
  const serialRatio = test => ({ ...test, ratio: roundRatio(test.ratio) });
  const data = {
    source: 'Current canonical shared/light/dark token sets and context-policy.json; regenerated by build.mjs.',
    scope: { textMinimum: 4.5, focusAndFunctionalEdgeMinimum: 3, neutralSurfaces: surfaces, contexts: 'light/dark × standard/more', thresholdEvaluation: 'Unrounded ratios', limitations: ['Opaque resting pairs only; overlays and glass require composite testing.', 'No browser or application validation is claimed.', 'Forced colors use native system colors.', 'No proposal or usage mapping is applied.'] },
    contexts: contexts.map(context => ({ ...context, tests: context.tests.map(serialRatio), failures: context.failures.map(serialRatio) })), failureCount: failures.length,
  };
  const markdown = [
    '# Color contrast review',
    'Generated from the current [master collection](../../master-tokens/Master-Token-List.md). Rebuild with `node master-tokens/scripts/build.mjs`. Token roles and usage mappings are unchanged.',
    '## Current findings',
    `${contexts.reduce((sum, context) => sum + context.tests.length, 0)} opaque color-pair checks cover light/dark and standard/enhanced contrast. ${failures.length} context/pair checks fall below their existing targets. Targets are evaluated before rounding.`,
    failureTable,
    'Below-target results remain unresolved. Each listed pair is registered in [known-contrast-exceptions.json](../../master-tokens/known-contrast-exceptions.json) as a diagnostic exception. Any below-target pair that is not registered fails the color check, and approved usage families cannot be registered. This review also includes tinted focus parents and ordinary resting text. These findings do not authorize different color values or usage mappings.',
    '## Neutral resting text',
    'Each cell compares the named ink with the surface column. Values are contrast ratios; “below target” means less than 4.5:1.',
    textTable,
    '## Focus and functional control edges',
    'Each cell compares the named color with the neutral parent surface. The existing target is 3:1. Validate actual adjacency and component states separately.',
    boundaryTable,
    '## Other opaque text pairs',
    table(['Theme', 'Contrast', 'Family', 'Minimum ratio', 'Below target'], contexts.flatMap(context => ['Enabled primary label', 'Status text on soft background', 'Status text on solid fill', 'Brand text on soft background'].map(family => { const tests = context.tests.filter(test => test.family === family); return [context.appearance, context.contrast, family, Math.min(...tests.map(test => test.ratio)).toFixed(4) + ':1', tests.some(test => !test.passes) ? 'Yes' : 'No']; }))),
    '## Scope and history',
    'The checks cover opaque resting text, enabled primary labels, status text, brand text, focus on neutral/brand/status parents, and control edges on neutral parents. Disabled text, hover/pressed overlay composites, glass, charts, gradients and rendered components require their own checks. Native forced colors use system colors, so no fixed hex contrast is inferred for that mode. These are calculations, not browser or application certification.',
    'The [earlier borderless review](archive/before-color-update-2026-10-28/Contrast-Review.md) and its [calculated results](archive/before-color-update-2026-10-28/results.json) are archived with the previous palette. Its inverted field pair was rejected as a default, and its dark-button proposal with black labels was not approved. Enabled primary labels continue to use `rds.color.ink.on-brand`.',
    'Complete current values and pair inventory: [results.json](results.json). Color changes: [before/after report](../color-value-update/Changes.md).',
  ].join('\n\n') + '\n';
  return { data, markdown, textTable, boundaryTable, failures };
}
