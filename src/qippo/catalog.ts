export function getQippoComponent(id: string) {
  return QIPPO_CATALOG.find((item) => item.id === id);
}

export function qippoByPresence(presence: QippoPresence) {
  return QIPPO_CATALOG.filter((item) => item.presence === presence);
}

export const QIPPO_REVIEW_FIRST = QIPPO_CATALOG.filter(
  (item) => item.reviewPriority != null
).sort((a, b) => (a.reviewPriority ?? 99) - (b.reviewPriority ?? 99));

export function qippoOnlyInventoryItems(): InventoryItem[] {
  return QIPPO_CATALOG.filter((item) => item.presence === 'qippo-only' && !item.mappedInventoryId).map(
    (item) => ({
      id: item.id,
      name: item.name,
      category: item.category,
      status: 'needs-review' as const,
      presence: item.presence,
      qippoSource: item.figmaPath,
      notes: item.summary,
      variants: item.variants,
      states: item.states,
      productSpecific: item.id === 'qippo-logo' || item.id === 'bank-logos',
    })
  );
}
