import type { InventoryCategory, InventoryItem } from '../inventory/catalog';
import { QIPPO_FIGMA, qippoFigmaUrl } from './figma';

export type QippoPresence = 'mapped' | 'qippo-only' | 'qipper-only' | 'needs-review';
export type QippoConfidence = 'high' | 'medium' | 'needs-review';

export interface QippoComponentRef {
  id: string;
  name: string;
  nameFa: string;
  category: InventoryCategory;
  presence: QippoPresence;
  confidence: QippoConfidence;
  section: string;
  nodeId: string;
  figmaUrl: string;
  figmaPath: string;
  screenshot?: string;
  screenshots?: string[];
  variants: string[];
  sizes: string[];
  states: string[];
  summary: string;
  differences: string[];
  reviewPriority?: number;
  /** Inventory ids this maps onto. Empty when Qippo-only with no inventory row yet. */
  mappedInventoryId?: string;
}

function ref(
  partial: Omit<QippoComponentRef, 'figmaUrl' | 'figmaPath'> & { figmaPath?: string }
): QippoComponentRef {
  return {
    ...partial,
    figmaUrl: qippoFigmaUrl(partial.nodeId),
    figmaPath:
      partial.figmaPath ??
      `${QIPPO_FIGMA.fileName} / ${QIPPO_FIGMA.pageName} / ${partial.section} / ${partial.nodeId}`,
  };
}

